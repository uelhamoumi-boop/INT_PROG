# Exercici 4.1 - Operadors aritmètics i lògics

# (a) Blocs: declaració > operacions > condicions
# (b) Exemple pràctic d’ús de variables i expressions
# (c) Compatible amb IDE

x = 10
y = 5

# Operacions aritmètiques
print("Suma:", x + y)
print("Resta:", x - y)
print("Multiplicació:", x * y)
print("Divisió:", x / y)
print("Mòdul:", x % y)

# Operadors de comparació i lògics
print("x és més gran que y:", x > y)
print("x és igual a y:", x == y)

# (g) Operadors lògics
print("x > y i el mòdul de x és 0:", x > y and x % 2 == 0)

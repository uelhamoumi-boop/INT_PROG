# Exercici 4.2 - Operador in i not in

frutes = ["poma", "plàtan", "taronja", "kiwi", "pera", "tomaca", "raïm"]

# Entrada
fruta = input("Introdueix el nom d’un fruta: ")

# Comprovacions amb in i not in
if fruta in frutes:
    print(f"La fruta {fruta} es troba a la llista.")
else:
    print(f"La fruta {fruta} no es troba a la llista.")

